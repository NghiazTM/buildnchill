-- ---------- 1. Trạng thái server: nhịp tim từ plugin ----------
CREATE TABLE IF NOT EXISTS public.server_status (
  id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  status TEXT DEFAULT 'Offline',
  players TEXT DEFAULT '0',
  max_players TEXT DEFAULT '500',
  version TEXT DEFAULT '1.20.4'
);
ALTER TABLE public.server_status ADD COLUMN IF NOT EXISTS last_seen TIMESTAMPTZ;
ALTER TABLE public.server_status ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ DEFAULT now();

INSERT INTO public.server_status (id, status, players, max_players, version)
OVERRIDING SYSTEM VALUE
SELECT 1, 'Offline', '0', '500', '1.20.4'
WHERE NOT EXISTS (SELECT 1 FROM public.server_status WHERE id = 1);

-- Bật realtime cho bảng (để web đổi trạng thái ngay khi có nhịp tim)
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_publication WHERE pubname = 'supabase_realtime')
     AND NOT EXISTS (SELECT 1 FROM pg_publication_tables WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename = 'server_status') THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.server_status;
  END IF;
END $$;

-- Plugin gọi (qua Netlify function, service role) mỗi chu kỳ.
-- Chỉ ghi DB khi có thay đổi hoặc đã quá 50 giây -> tránh spam realtime.
CREATE OR REPLACE FUNCTION public.bnc_server_heartbeat(p_players INT, p_max INT DEFAULT NULL, p_version TEXT DEFAULT NULL)
RETURNS VOID
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
  UPDATE public.server_status
     SET status = 'Online',
         players = greatest(coalesce(p_players, 0), 0)::text,
         max_players = coalesce(p_max::text, max_players),
         version = coalesce(nullif(trim(p_version), ''), version),
         last_seen = now(),
         updated_at = now()
   WHERE id = 1
     AND (
       last_seen IS NULL
       OR last_seen < now() - interval '50 seconds'
       OR status IS DISTINCT FROM 'Online'
       OR players IS DISTINCT FROM greatest(coalesce(p_players, 0), 0)::text
       OR (p_max IS NOT NULL AND max_players IS DISTINCT FROM p_max::text)
       OR (nullif(trim(p_version), '') IS NOT NULL AND version IS DISTINCT FROM trim(p_version))
     );
$$;
REVOKE EXECUTE ON FUNCTION public.bnc_server_heartbeat(INT, INT, TEXT) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.bnc_server_heartbeat(INT, INT, TEXT) TO service_role;

-- Chỉ admin được sửa trạng thái thủ công (trước đây mọi tài khoản đăng nhập đều sửa được)
ALTER TABLE public.server_status ENABLE ROW LEVEL SECURITY;
DO $$
DECLARE pol RECORD;
BEGIN
  FOR pol IN SELECT policyname FROM pg_policies WHERE schemaname = 'public' AND tablename = 'server_status' LOOP
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.server_status', pol.policyname);
  END LOOP;
END $$;
CREATE POLICY "bnc status public read" ON public.server_status FOR SELECT USING (true);
CREATE POLICY "bnc status admin write" ON public.server_status FOR ALL USING (public.is_admin()) WITH CHECK (public.is_admin());
GRANT SELECT ON public.server_status TO anon, authenticated;
GRANT UPDATE ON public.server_status TO authenticated;

-- ---------- 2. Nhiều tài khoản nhận tiền ----------
CREATE TABLE IF NOT EXISTS public.payment_accounts (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  bank_code TEXT NOT NULL,            -- mã VietQR: MB, VCB, TCB, ACB, BIDV, ICB, VBA, TPB, VPB...
  bank_name TEXT NOT NULL,            -- tên hiển thị: MB Bank, Vietcombank...
  account_number TEXT NOT NULL,
  account_name TEXT NOT NULL,         -- tên chủ tài khoản (IN HOA, không dấu)
  note TEXT,
  is_active BOOLEAN NOT NULL DEFAULT true,
  display_order INT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
ALTER TABLE public.payment_accounts ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "bnc banks public read" ON public.payment_accounts;
DROP POLICY IF EXISTS "bnc banks admin write" ON public.payment_accounts;
CREATE POLICY "bnc banks public read" ON public.payment_accounts FOR SELECT USING (is_active = true OR public.is_admin());
CREATE POLICY "bnc banks admin write" ON public.payment_accounts FOR ALL USING (public.is_admin()) WITH CHECK (public.is_admin());
GRANT SELECT ON public.payment_accounts TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON public.payment_accounts TO authenticated;

